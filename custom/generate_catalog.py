"""Generate the C/C++ Chinese table; reject missing entries or changed printf arguments."""
import ast
import json
from pathlib import Path
import re

ROOT=Path(__file__).resolve().parents[1]
LITERAL=r'"(?:\\.|[^"\\])*"'
FORMAT=re.compile(r'%(?!APPDATA%)(?:[-+ #0]*\d*(?:\.\d+)?(?:ll|l|z)?[sdiuoxXfFgGcpaAeE])')

def generate(check=False):
    translations=json.loads((ROOT/'custom/zh-CN.json').read_text(encoding='utf-8'))
    text=(ROOT/'runtime/settings_locale.h').read_text(encoding='utf-8')
    keys=[ast.literal_eval(re.findall(LITERAL,row)[0]) for row in
          re.findall(r'\{\s*'+LITERAL+r'\s*,\s*'+LITERAL+r'\s*\}',text)]
    missing=set(keys)-translations.keys()
    if missing:raise ValueError('Missing Chinese labels: '+repr(sorted(missing)))
    for en,zh in translations.items():
        if not zh or '\ufffd' in zh or '\0' in zh:raise ValueError('Invalid Chinese text: '+en)
        if FORMAT.findall(en)!=FORMAT.findall(zh):raise ValueError('printf arguments differ: '+en)
        if '###' in en and en.split('###',1)[1]!=zh.split('###',1)[1]:raise ValueError('ImGui ID differs: '+en)
    result='// Generated by custom/generate_catalog.py. Host UI only; MIT.\n#pragma once\n#include <string.h>\n#include <stdio.h>\n'
    result+='static inline const char *settings_chinese(const char *english) {\n'
    result+='    static const struct { const char *en, *zh; } messages[] = {\n'
    for en,zh in sorted(translations.items()):result+='        {'+json.dumps(en,ensure_ascii=False)+', '+json.dumps(zh,ensure_ascii=False)+'},\n'
    result+='    };\n    for (unsigned i=0; i<sizeof messages/sizeof *messages; ++i)\n        if (!strcmp(english,messages[i].en)) return messages[i].zh;\n'
    result+='''    if (!strncmp(english,"Default: ",9)) {
#ifdef __cplusplus
        static thread_local char value[512];
#else
        static _Thread_local char value[512];
#endif
        snprintf(value,sizeof value,"默认：%s",settings_chinese(english+9));
        return value;
    }
    return english;
}
'''
    path=ROOT/'runtime/settings_zh.h'
    if check:
        if not path.exists() or path.read_text(encoding='utf-8')!=result:raise ValueError('Generated Chinese header is stale')
    else:path.write_text(result,encoding='utf-8')
    print('Chinese catalog:',len(translations),'entries; all UI keys/printf arguments verified.')

if __name__=='__main__':
    import sys
    generate('--check' in sys.argv)
